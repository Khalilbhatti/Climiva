/**
 * Assets and Organization Branding.
 *
 *     Organization  ->  many Assets      (files a business owns: today only its logo)
 *     Organization  ->  one Branding     (the business's central identity: its logo and its accent)
 *
 * An Asset row is METADATA. The bytes live in object storage (src/storage: a local directory in development, a private S3 bucket in
 * production), never in PostgreSQL, and are reached only through `storage_key`, which the application generates and the CHECK below ties
 * to the row's own organization and id, so a key can never point into another business's folder. A browser never sees a key: it sees
 * `/assets/<id>` (src/lib/asset-rules `assetUrl`), and the public route serves an Asset only while it is the logo a business has chosen.
 *
 * Lifecycle (the database and the object store cannot share a transaction, so the order is deliberate):
 *     pending  -> ready      the object is stored and the row says so; only ready Assets can be a logo or be served
 *     pending  -> failed     the upload did not complete; never served, never referenced
 *     ready    -> deleted    a soft delete for a later garbage collector; no row is ever deleted through the application
 *
 * Organization Branding is the business's CENTRAL identity (the logo, the accent). It is not a Site's Theme: a Site Version keeps its own
 * design tokens, which can differ between two Sites of one business, and neither is copied into the other. The logo is read when a page
 * is drawn, so changing it needs no Publish and a Template change does not touch it.
 *
 * `organization_branding` reaches `assets` through a composite (organization_id, id) foreign key, so a Branding row cannot reference another
 * business's Asset: PostgreSQL's referential checks run outside Row Level Security, which makes it impossible rather than merely checked.
 * That the Asset is a READY logo is a guard in the database (drizzle/0018).
 */
import { sql } from "drizzle-orm";
import { check, foreignKey, index, integer, pgTable, text, timestamp, unique, uuid } from "drizzle-orm/pg-core";
import { authUser } from "./auth";
import { organizations } from "./organizations";

export const ASSET_PURPOSES = ["logo"] as const;
export type AssetPurpose = (typeof ASSET_PURPOSES)[number];
export const ASSET_STATUSES = ["pending", "ready", "failed", "deleted"] as const;
export type AssetStatus = (typeof ASSET_STATUSES)[number];
export const ASSET_STORAGE_DRIVERS = ["local", "s3"] as const;
export type AssetStorageDriver = (typeof ASSET_STORAGE_DRIVERS)[number];
/** What a stored (normalized) image may be. Uploads are re-encoded, so SVG and anything animated or scriptable is never stored. */
export const ASSET_MEDIA_TYPES = ["image/webp", "image/png", "image/jpeg"] as const;

const list = (values: readonly string[]) => sql.raw(values.map((value) => `'${value}'`).join(", "));

export const assets = pgTable(
  "assets",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    organizationId: uuid("organization_id")
      .notNull()
      .references(() => organizations.id, { onDelete: "restrict" }),
    purpose: text("purpose").notNull(),
    storageDriver: text("storage_driver").notNull(),
    /** `organizations/<organization id>/assets/<asset id>/normalized`: generated by the application, never from a filename. */
    storageKey: text("storage_key").notNull().unique(),
    /** What the person called the file. Display only: it is never part of a key, a path or a response header. */
    originalFilename: text("original_filename"),
    /** The type of the STORED bytes (the upload is re-encoded), never the type the browser claimed. */
    mediaType: text("media_type").notNull(),
    byteSize: integer("byte_size").notNull(),
    width: integer("width"),
    height: integer("height"),
    /** SHA-256 of the stored bytes, lower-case hex. Integrity only: it is never used to decide who may read. */
    checksum: text("checksum").notNull(),
    status: text("status").notNull().default("pending"),
    createdByUserId: text("created_by_user_id").references(() => authUser.id, { onDelete: "set null" }),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    readyAt: timestamp("ready_at", { withTimezone: true }),
    deletedAt: timestamp("deleted_at", { withTimezone: true }),
  },
  (table) => [
    // The target of the composite foreign keys that make a cross-organization reference impossible.
    unique("assets_org_id_key").on(table.organizationId, table.id),
    index("assets_org_purpose_status_idx").on(table.organizationId, table.purpose, table.status),
    check("assets_purpose", sql`${table.purpose} in (${list(ASSET_PURPOSES)})`),
    check("assets_status", sql`${table.status} in (${list(ASSET_STATUSES)})`),
    check("assets_storage_driver", sql`${table.storageDriver} in (${list(ASSET_STORAGE_DRIVERS)})`),
    check("assets_media_type", sql`${table.mediaType} in (${list(ASSET_MEDIA_TYPES)})`),
    check("assets_byte_size", sql`${table.byteSize} between 1 and 10485760`),
    check("assets_dimensions", sql`(${table.width} is null or ${table.width} > 0) and (${table.height} is null or ${table.height} > 0)`),
    check("assets_checksum", sql`${table.checksum} ~ '^[0-9a-f]{64}$'`),
    check("assets_original_filename", sql`${table.originalFilename} is null or char_length(${table.originalFilename}) between 1 and 255`),
    // The key can only be the row's own: another business's folder, or another Asset's, is not expressible.
    check("assets_storage_key_own", sql`${table.storageKey} = 'organizations/' || ${table.organizationId}::text || '/assets/' || ${table.id}::text || '/normalized'`),
    check(
      "assets_lifecycle",
      sql`(${table.status} = 'pending' and ${table.readyAt} is null and ${table.deletedAt} is null)
        or (${table.status} = 'failed' and ${table.readyAt} is null and ${table.deletedAt} is null)
        or (${table.status} = 'ready' and ${table.readyAt} is not null and ${table.deletedAt} is null)
        or (${table.status} = 'deleted' and ${table.deletedAt} is not null)`,
    ),
  ],
).enableRLS();

export const organizationBranding = pgTable(
  "organization_branding",
  {
    /** One row per organization. It is created when a business first saves its Branding; no row means no logo and no accent. */
    organizationId: uuid("organization_id")
      .primaryKey()
      .references(() => organizations.id, { onDelete: "restrict" }),
    /** The current logo: one of THIS organization's ready logo Assets, or null (the business's initials are shown instead). */
    logoAssetId: uuid("logo_asset_id"),
    /** "#RRGGBB", or null for the Climvia teal. The base colour of customer-facing frames inside the workspace; a Site Theme's own accent wins. */
    accent: text("accent"),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => [
    foreignKey({ name: "organization_branding_logo_fk", columns: [table.organizationId, table.logoAssetId], foreignColumns: [assets.organizationId, assets.id] }).onDelete("restrict"),
    check("organization_branding_accent", sql`${table.accent} is null or ${table.accent} ~ '^#[0-9A-F]{6}$'`),
  ],
).enableRLS();

export type AssetRow = typeof assets.$inferSelect;
export type BrandingRow = typeof organizationBranding.$inferSelect;
